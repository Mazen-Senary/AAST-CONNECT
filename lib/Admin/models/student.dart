class Student {
  final String id;
  final String name;
  final String email;
  final String major;
  final String year;
  final double gpa;
  final int applications;
  final int trainingHours;

  Student({
    required this.id,
    required this.name,
    required this.email,
    required this.major,
    required this.year,
    required this.gpa,
    required this.applications,
    required this.trainingHours,
  });
}
